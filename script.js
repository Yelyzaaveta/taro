function pickRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function isReversed() {
  return Math.random() < 0.3;
}

// Mode switching
const modeBtns = document.querySelectorAll('.mode-btn');
const tarotSection = document.getElementById('tarot-section');
const runesSection = document.getElementById('runes-section');

modeBtns.forEach(btn => {
  btn.addEventListener('click', () => {
    modeBtns.forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    if (btn.dataset.mode === 'tarot') {
      tarotSection.classList.remove('hidden');
      runesSection.classList.add('hidden');
    } else {
      tarotSection.classList.add('hidden');
      runesSection.classList.remove('hidden');
    }
  });
});

// Tarot — card flip
const cardEl = document.getElementById('card');
const cardFront = document.getElementById('card-front');
const cardNumeral = document.getElementById('card-numeral');
const cardSymbol = document.getElementById('card-symbol');
const cardTitle = document.getElementById('card-title');
const tarotResult = document.getElementById('tarot-result');
let cardFlipped = false;

document.getElementById('card-wrapper').addEventListener('click', () => {
  const card = pickRandom(tarotCards);
  const rev = isReversed();

  if (cardFlipped) {
    // Reset: flip back first, then after animation show new card
    cardEl.classList.remove('flipped');
    cardFront.classList.remove('reversed');
    tarotResult.classList.add('hidden');
    cardFlipped = false;

    setTimeout(() => showCard(card, rev), 700);
  } else {
    showCard(card, rev);
  }
});

function showCard(card, rev) {
  // Fill card face
  cardNumeral.textContent = card.numeral;
  cardSymbol.textContent = card.symbol;
  cardTitle.innerHTML = card.name + (rev ? '<div class="reversed-label">Перевернута</div>' : '');

  if (rev) {
    cardFront.classList.add('reversed');
  } else {
    cardFront.classList.remove('reversed');
  }

  // Flip
  cardEl.classList.add('flipped');
  cardFlipped = true;

  // Show meaning below after flip animation
  setTimeout(() => {
    tarotResult.classList.remove('hidden');
    tarotResult.innerHTML = `
      <div class="result-meaning">${rev ? card.reversed : card.meaning}</div>
    `;
    tarotResult.style.animation = 'none';
    tarotResult.offsetHeight;
    tarotResult.style.animation = 'slideUp 0.4s ease';
  }, 600);
}

// Runes
const throwBtn = document.getElementById('throw-runes');
const runesResult = document.getElementById('runes-result');

throwBtn.addEventListener('click', () => {
  const count = Math.floor(Math.random() * 3) + 1;
  const picked = [];
  const used = new Set();

  while (picked.length < count) {
    const idx = Math.floor(Math.random() * runes.length);
    if (!used.has(idx)) {
      used.add(idx);
      picked.push({ rune: runes[idx], reversed: isReversed() });
    }
  }

  const stonesHTML = picked.map(p =>
    `<div class="rune-stone" ${p.reversed ? 'style="transform:rotate(180deg)"' : ''}>${p.rune.symbol}</div>`
  ).join('');

  const meaningsHTML = picked.map((p, i) => `
    ${i > 0 ? '<hr class="rune-divider">' : ''}
    <div>
      ${p.reversed ? '<div class="reversed-badge">Перевернута</div>' : ''}
      <div class="result-name">${p.rune.name}</div>
      <div class="result-meaning">${p.reversed ? p.rune.reversed : p.rune.meaning}</div>
    </div>
  `).join('');

  runesResult.classList.remove('hidden');
  runesResult.innerHTML = `
    <div class="rune-stones">${stonesHTML}</div>
    ${meaningsHTML}
  `;
  runesResult.style.animation = 'none';
  runesResult.offsetHeight;
  runesResult.style.animation = 'slideUp 0.4s ease';
});
